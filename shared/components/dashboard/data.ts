function scaleManagers(
  rows: typeof managersThisWeek,
  factor: number,
): typeof managersThisWeek {
  return rows.map((row) => ({
    ...row,
    conversations: Math.max(1, Math.round(row.conversations * factor)),
    score: Number((row.score + (factor - 1) * 1.2).toFixed(1)),
    script: Number((row.script + (factor - 1) * 0.8).toFixed(1)),
    talkShare: Number((row.talkShare - (factor - 1) * 0.4).toFixed(1)),
    nextStep: Number((row.nextStep + (factor - 1) * 1.4).toFixed(1)),
  }))
}


function anonymizeCallClients(calls: CallRecord[]): CallRecord[] {
  const labels = new Map<string, string>()
  let n = 0
  return calls.map((call) => {
    const key = call.company !== '—' ? call.company : call.client
    let label = labels.get(key)
    if (!label) {
      n += 1
      label = `Клиент ${n}`
      labels.set(key, label)
    }
    return { ...call, client: label, company: label }
  })
}

